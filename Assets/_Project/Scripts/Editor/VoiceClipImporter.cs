using System;
using System.IO;
using System.Linq;
using System.Text;
using UnityEditor;
using UnityEngine;
using TheLightHouse.Voice;

namespace TheLightHouse.Editor
{
    public static class VoiceClipImporter
    {
        public const string VoiceAudioRoot = "Assets/_Project/Audio/Voice";

        [MenuItem("TheLightHouse/Voice/Import Voice Clips")]
        public static void ImportClips()
        {
            var db = AssetDatabase.LoadAssetAtPath<VoiceDatabase>(VoiceDatabaseBuilder.DatabasePath);
            if (!db) db = VoiceDatabaseBuilder.BuildDatabase();

            int matched = 0;
            var wavFiles = Directory.GetFiles(VoiceAudioRoot, "*.wav", SearchOption.AllDirectories);

            foreach (var file in wavFiles)
            {
                string lineId = Path.GetFileNameWithoutExtension(file);
                if (db.TryGetLine(lineId, out var line))
                {
                    ConfigureImporter(file);
                    var clip = AssetDatabase.LoadAssetAtPath<AudioClip>(file);
                    if (clip)
                    {
                        line.Clip = clip;
                        // If file was generated by macOS say placeholder, keep isPlaceholder = true, otherwise false
                        if (line.Clip != null && !file.Contains("Placeholder"))
                        {
                            line.IsPlaceholder = false;
                        }
                        EditorUtility.SetDirty(line);
                        matched++;
                    }
                }
            }

            AssetDatabase.SaveAssets();
            Debug.Log($"[VoiceClipImporter] Scanned {wavFiles.Length} audio files. Matched and updated {matched} VoiceLine assets.");
        }

        public static void ConfigureImporter(string assetPath)
        {
            var importer = AssetImporter.GetAtPath(assetPath) as AudioImporter;
            if (!importer) return;

            bool dirty = false;
            if (!importer.forceToMono)
            {
                importer.forceToMono = true;
                dirty = true;
            }

            var settings = importer.defaultSampleSettings;
            if (settings.compressionFormat != AudioCompressionFormat.Vorbis)
            {
                settings.compressionFormat = AudioCompressionFormat.Vorbis;
                dirty = true;
            }

            if (Mathf.Abs(settings.quality - 0.40f) > 0.01f)
            {
                settings.quality = 0.40f;
                dirty = true;
            }

            if (settings.sampleRateSetting != AudioSampleRateSetting.OverrideSampleRate || settings.sampleRateOverride != 44100)
            {
                settings.sampleRateSetting = AudioSampleRateSetting.OverrideSampleRate;
                settings.sampleRateOverride = 44100;
                dirty = true;
            }

            // Load type based on clip length if accessible
            var tempClip = AssetDatabase.LoadAssetAtPath<AudioClip>(assetPath);
            if (tempClip != null)
            {
                if (tempClip.length >= 6.0f)
                {
                    if (settings.loadType != AudioClipLoadType.Streaming)
                    {
                        settings.loadType = AudioClipLoadType.Streaming;
                        settings.preloadAudioData = false;
                        dirty = true;
                    }
                }
                else
                {
                    if (settings.loadType != AudioClipLoadType.CompressedInMemory)
                    {
                        settings.loadType = AudioClipLoadType.CompressedInMemory;
                        settings.preloadAudioData = true;
                        dirty = true;
                    }
                }
            }

            if (dirty)
            {
                importer.defaultSampleSettings = settings;
                importer.SaveAndReimport();
            }
        }

        [MenuItem("TheLightHouse/Voice/Coverage Report")]
        public static string GenerateCoverageReport()
        {
            var db = AssetDatabase.LoadAssetAtPath<VoiceDatabase>(VoiceDatabaseBuilder.DatabasePath);
            if (!db) db = VoiceDatabaseBuilder.BuildDatabase();

            var sb = new StringBuilder();
            sb.AppendLine("================================================================================");
            sb.AppendLine("THE LIGHTHOUSE: HARROW ROCK — VOICE ASSET COVERAGE REPORT");
            sb.AppendLine("================================================================================");

            int totalLines = db.AllLines.Count;
            int recorded = db.AllLines.Count(l => l.Clip != null && !l.IsPlaceholder);
            int placeholder = db.AllLines.Count(l => l.Clip != null && l.IsPlaceholder);
            int missing = db.AllLines.Count(l => l.Clip == null);

            sb.AppendLine($"Total Voice Lines:  {totalLines}");
            sb.AppendLine($"Recorded (Final):   {recorded} ({recorded * 100f / totalLines:F1}%)");
            sb.AppendLine($"Placeholder (WAV):  {placeholder} ({placeholder * 100f / totalLines:F1}%)");
            sb.AppendLine($"Missing Audio:      {missing} ({missing * 100f / totalLines:F1}%)");
            sb.AppendLine();
            sb.AppendLine("Coverage by Character:");
            sb.AppendLine("--------------------------------------------------------------------------------");
            sb.AppendLine($"{"Speaker",-16} | {"Total",-6} | {"Final",-6} | {"Placehd",-7} | {"Missing",-7} | {"Coverage",-8}");
            sb.AppendLine("--------------------------------------------------------------------------------");

            foreach (SpeakerId spk in Enum.GetValues(typeof(SpeakerId)))
            {
                var spkLines = db.GetLinesBySpeaker(spk);
                int spkTotal = spkLines.Count;
                if (spkTotal == 0) continue;
                int spkRec = spkLines.Count(l => l.Clip != null && !l.IsPlaceholder);
                int spkPlh = spkLines.Count(l => l.Clip != null && l.IsPlaceholder);
                int spkMis = spkLines.Count(l => l.Clip == null);
                float cov = (spkRec + spkPlh) * 100f / spkTotal;

                sb.AppendLine($"{spk,-16} | {spkTotal,-6} | {spkRec,-6} | {spkPlh,-7} | {spkMis,-7} | {cov,7:F1}%");
            }

            sb.AppendLine();
            sb.AppendLine("Coverage by Act:");
            sb.AppendLine("--------------------------------------------------------------------------------");
            for (int act = 1; act <= 5; act++)
            {
                var actLines = db.GetLinesByAct(act);
                int aTotal = actLines.Count;
                int aHave = actLines.Count(l => l.Clip != null);
                sb.AppendLine($"Act {act}: {aHave}/{aTotal} audio clips available ({(aTotal > 0 ? aHave * 100f / aTotal : 0):F1}%)");
            }

            sb.AppendLine("================================================================================");
            string report = sb.ToString();
            Debug.Log(report);
            return report;
        }
    }
}
